"""
Modo automático: el servidor encadena las cinco etapas (ontología → grafo →
preparación → simulación → informe) aunque el usuario cierre la pestaña.

Hace la misma secuencia y con los mismos parámetros que la pantalla, llamando
a las mismas rutas con `app.test_client()` y el secreto interno del proceso
(sin token de usuario y sin contar para el rate limit). La única etapa que no
pasa por una ruta es la ontología: el proyecto se crea en la petición y la
ontología se genera aquí con el mismo helper que usa `ontology/generate`.

Cada etapa comprueba primero si ya está hecha, así que reanudar es volver a
recorrerlas: se saltan las completadas y se reutilizan proyecto, grafo,
simulación e informe.
"""

