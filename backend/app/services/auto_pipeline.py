# ============== Tiempos ==============

GRAPH_TIMEOUT_SECONDS = 30 * 60
PREPARE_TIMEOUT_SECONDS = 30 * 60
SIMULATION_TIMEOUT_SECONDS = 6 * 60 * 60
REPORT_TIMEOUT_SECONDS = 45 * 60
POLL_SECONDS = 5
# Margen para una simulación que otro (la pantalla) está arrancando justo ahora
STARTING_GRACE_SECONDS = 60

# ============== Parámetros: los mismos que manda la pantalla ==============

