def start_pipeline(
    app,
    project_id: str,
    *,
    locale: str,
    document_texts=None,
    additional_context: Optional[str] = None,
) -> Dict[str, Any]:
    """
    Arranca el modo automático (proyecto recién creado, con `document_texts`)
    o lo reanuda desde la primera etapa sin completar. PipelineConflict si ya
    hay una ejecución viva para el proyecto.
    """
    with pipeline_lock(project_id):
        current = read_pipeline(project_id)
        if current and current.get("status") == "running":
            if _is_run_alive(project_id, current.get("run_id")):
                raise PipelineConflict("Ya hay un modo automático en marcha para este proyecto")
            logger.warning(f"[pipeline {project_id}] Estado running sin hilo vivo: se releva")

        project = ProjectManager.get_project(project_id)
        if project is None:
            raise LookupError(project_id)

        previous_stage = current.get("stage") if current else None
        if additional_context is None and current:
            additional_context = current.get("additional_context") or None

        if document_texts is not None:
            stage, simulation_id = "ontology", None
        else:
            stage, simulation_id = _estimate_stage(project, previous_stage)

        run_id = uuid.uuid4().hex
        state = {
            "mode": "auto",
            "status": "running",
            "stage": stage,
            "project_id": project_id,
            "simulation_id": simulation_id,
            "report_id": None,
            "error": None,
            "started_at": now_iso(),
            "finished_at": None,
            # Internos (no salen al cliente)
            "run_id": run_id,
            "additional_context": additional_context or "",
        }
        write_pipeline(project_id, state)

        runner = AutoPipelineRunner(
            app,
            project_id,
            run_id,
            locale,
            previous_stage=previous_stage,
            document_texts=document_texts,
            additional_context=additional_context,
        )
        _register(runner)
        runner.thread.start()

    logger.info(f"[pipeline {project_id}] Modo automático lanzado desde la etapa «{stage}»")
    return public_view(state)


def cancel_pipeline(app, project_id: str, *, locale: str) -> Dict[str, Any]:
    """Para el bucle y detiene la simulación si corre. Idempotente."""
    simulation_to_stop = None
    with pipeline_lock(project_id):
        state = read_pipeline(project_id)
        if not state:
            return public_view(None)
        if state.get("status") == "running":
            state.update(status="cancelled", finished_at=now_iso(), error=None)
            write_pipeline(project_id, state)
            runner = active_runner(project_id)
            if runner and runner.run_id == state.get("run_id"):
                runner.cancel_event.set()
            simulation_to_stop = state.get("simulation_id")
            logger.info(f"[pipeline {project_id}] Modo automático cancelado en la etapa «{state.get('stage')}»")

    if simulation_to_stop:
        stop_simulation_if_running(InternalApiClient(app, locale), simulation_to_stop)
    return public_view(state)


def get_pipeline_state(project_id: str) -> Dict[str, Any]:
    with pipeline_lock(project_id):
        state = read_pipeline(project_id)
        if state and state.get("status") == "running" and not _is_run_alive(project_id, state.get("run_id")):
            # Ningún hilo de este proceso la lleva (no debería pasar sin reinicio)
            state.update(
                status="interrupted",
                finished_at=now_iso(),
                error="El modo automático se detuvo sin terminar. Puedes reanudarlo.",
            )
            write_pipeline(project_id, state)
    return public_view(state)


def get_pipeline_summary(project_id: str) -> Dict[str, Any]:
    """Para el historial: modo y estado, sin escribir nada."""
    state = read_pipeline(project_id)
    if not state or state.get("mode") != "auto":
        return {"pipeline_mode": "manual", "pipeline_status": None}
    status = state.get("status")
    if status == "running" and not _is_run_alive(project_id, state.get("run_id")):
        status = "interrupted"
    return {"pipeline_mode": "auto", "pipeline_status": status}
